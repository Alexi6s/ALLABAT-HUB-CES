// Generates docs/API.md, docs/openapi.json and docs/PERMISSIONS.md from the live route registry, so the docs cannot drift from the code.
//
//   npm run docs:api            write both files
//   npm run docs:api -- --check exit 1 if the committed files are out of date (used in CI)
//
// What it knows: method, path, who may call it (public / signed in / permission and the roles that hold it), rate limits,
// raw-body routes and routes open to suspended accounts. What it does NOT know: request and response bodies, because
// handlers validate input in code rather than from declared schemas. The OpenAPI file therefore describes access rules,
// not payload shapes, and says so in its description.
import fs from 'node:fs';
import path from 'node:path';
import '../apps/api/src/routes/identity.ts';
import '../apps/api/src/routes/mentors.ts';
import '../apps/api/src/routes/programmes.ts';
import '../apps/api/src/routes/funding.ts';
import '../apps/api/src/routes/platform.ts';
import '../apps/api/src/routes/admin.ts';
import '../apps/api/src/routes/support.ts';
import '../apps/api/src/routes/mentoring-ops.ts';
import '../apps/api/src/routes/analytics.ts';
import { listRoutes } from '../apps/api/src/http.ts';
import { PERMISSIONS, ROLES, STAFF_ROLES, PRIVILEGED_ROLES, CATEGORIES, REQUIRED_DOCUMENT, categoryRole } from '../apps/api/src/policy.ts';

const root = path.resolve(import.meta.dirname, '..');
const docsDir = path.join(root, 'docs');
const routes = listRoutes()
  .map((r) => ({ ...r, area: r.path.split('/')[2] ?? 'root' }))
  .sort((a, b) => a.area.localeCompare(b.area) || a.path.localeCompare(b.path) || a.method.localeCompare(b.method));

const access = (r: (typeof routes)[number]) =>
  r.auth === false ? 'Public' : r.perm ? `Permission \`${r.perm}\`` : 'Signed in';
const rolesFor = (perm: string) => (PERMISSIONS as Record<string, readonly string[]>)[perm]?.join(', ') ?? '';
const notes = (r: (typeof routes)[number]) =>
  [
    r.limit ? `max ${r.limit} requests per 15 min per IP` : '',
    r.raw ? 'raw request body (file upload)' : '',
    r.allowInactive ? 'also open to suspended accounts' : '',
  ].filter(Boolean).join('; ');

function markdown() {
  const out: string[] = [];
  out.push('# ALABATT-CES API reference', '');
  out.push('_Generated by `npm run docs:api` from the route registry. Do not edit by hand._', '');
  out.push(`${routes.length} endpoints. Every response is JSON except file downloads and CSV export.`, '');
  out.push('## Conventions', '');
  out.push('- **Session**: HttpOnly cookie `ces_session`, set by `POST /api/auth/login`.');
  out.push('- **CSRF**: every state-changing request must send `X-Requested-With: ALABATT`, and a browser `Origin` header, if present, must match this site.');
  out.push('- **Errors**: `{ "error": { "code", "message", "details"? } }`. `details` maps field names to messages for validation errors (HTTP 422).');
  out.push('- **Status codes**: 400 malformed request, 401 not signed in, 403 not permitted, step-up password wrong, or account not active/verified, 404 missing **or not yours**, 409 invalid state transition or capacity conflict, 422 field validation failed, 413 upload too large, 429 rate limited.');
  out.push('- **Authorization is enforced on the server** for every route below; the web client hides controls only as a convenience.');
  out.push('- **Request and response bodies are not declared here.** Handlers validate input in code. See `apps/api/src/routes/*.ts` and the tests in `apps/api/test/`.', '');
  out.push('## Permissions', '', '| Permission | Roles that hold it |', '|---|---|');
  for (const p of Object.keys(PERMISSIONS).sort()) out.push(`| \`${p}\` | ${rolesFor(p)} |`);
  out.push('');
  let area = '';
  for (const r of routes) {
    if (r.area !== area) {
      area = r.area;
      out.push('', `## /api/${area}`, '', '| Method | Path | Access | Notes |', '|---|---|---|---|');
    }
    out.push(`| ${r.method} | \`${r.path}\` | ${access(r)} | ${notes(r)} |`);
  }
  out.push('');
  return out.join('\n');
}

function openapi() {
  const paths: Record<string, Record<string, unknown>> = {};
  for (const r of routes) {
    const p = r.path.replace(/:([a-zA-Z_]+)/g, '{$1}');
    const params = [...r.path.matchAll(/:([a-zA-Z_]+)/g)].map((m) => ({ name: m[1], in: 'path', required: true, schema: { type: 'string' } }));
    (paths[p] ??= {})[r.method.toLowerCase()] = {
      tags: [r.area],
      summary: `${r.method} ${r.path}`,
      description: [access(r), r.perm ? `Roles: ${rolesFor(r.perm)}` : '', notes(r)].filter(Boolean).join('. '),
      ...(params.length ? { parameters: params } : {}),
      ...(r.auth === false ? { security: [] } : { security: [{ session: [] }] }),
      ...(r.perm ? { 'x-permission': r.perm } : {}),
      responses: { '200': { description: 'Success (JSON; shape defined by the handler).' }, '4XX': { description: 'Error envelope { error: { code, message, details? } }.' } },
    };
  }
  return {
    openapi: '3.0.3',
    info: {
      title: 'ALABATT-CES API',
      description: 'Generated from the route registry. Describes paths, methods and access rules only; request/response payload schemas are not declared in code and are therefore not included.',
      version: 'unversioned',
    },
    components: { securitySchemes: { session: { type: 'apiKey', in: 'cookie', name: 'ces_session' } } },
    paths,
  };
}

function permissionsDoc() {
  const out: string[] = [];
  out.push('# Roles and permissions', '');
  out.push('_The tables are generated by `npm run docs:api` from `apps/api/src/policy.ts`. Do not edit by hand._', '');
  out.push('Access is **deny by default**. Every protected route declares the permission it needs; the check runs before the request body is read, so an unauthorised caller learns nothing about the record. Record-level rules (you can only see your own ventures, applications, documents) are enforced in each handler and return **404** for records that belong to someone else.', '');
  out.push('## Three separate things', '');
  out.push('1. **Account category**: what you registered as (' + CATEGORIES.join(', ') + ', or staff). It is a claim until verified.');
  out.push('2. **Verification status**: unverified, pending, under review, more info required, verified, rejected. Institutional features need `verified` plus a confirmed email.');
  out.push('3. **Roles**: what the platform lets you do. Roles are never self-assigned (see rules below).', '');
  out.push('## Required evidence per category', '', '| Category | Required document | Role granted when verification is approved |', '|---|---|---|');
  for (const c of CATEGORIES) out.push(`| ${c} | ${REQUIRED_DOCUMENT[c] ?? ''} | ${categoryRole(c) ?? '(none: the mentor role comes only from mentor review)'} |`);
  out.push('', '## What each role can do through the permission map', '');
  out.push('Member roles (' + ROLES.filter((r) => !STAFF_ROLES.includes(r) && r !== 'mentor' && r !== 'lecturer').join(', ') + ') hold no staff permission. What they can do is defined by ownership and verification, not by this map. `lecturer` and `mentor` additionally hold `resource.create`.', '', '| Role | Permissions |', '|---|---|');
  for (const r of ROLES) {
    const ps = Object.keys(PERMISSIONS).filter((p) => (PERMISSIONS as Record<string, readonly string[]>)[p].includes(r)).sort();
    out.push(`| ${r} | ${ps.length ? ps.map((p) => `\`${p}\``).join(', ') : '(none)'} |`);
  }
  out.push('', '## Permission to roles', '', '| Permission | Roles |', '|---|---|');
  for (const p of Object.keys(PERMISSIONS).sort()) out.push(`| \`${p}\` | ${rolesFor(p)} |`);
  out.push('', '## Governance rules (each one has an automated test)', '');
  out.push(`- **Roles come only from governance.** Verification approval grants the category role. Mentor review grants \`mentor\`. Administrators grant only staff roles (${STAFF_ROLES.join(', ')}). Granting or revoking ${PRIVILEGED_ROLES.join(' or ')} needs a super administrator. Nobody can change their own roles, and the last super administrator cannot be removed.`);
  out.push('- **Changing affiliation resets trust.** Editing institutional details sets verification back to unverified and removes the category role until a reviewer approves again.');
  out.push('- **Separation of duties.** You cannot decide your own verification, review your own mentor application, decide your own programme application, or review a venture, review a milestone, evaluate funding, or disburse funds for a venture you belong to. The person who disburses a grant must differ from the person who approved it; even a super administrator cannot pay their own approval. Disbursement needs a signed agreement and `funding.disburse`.');
  out.push('- **Account status.** A suspended user may sign in but can only reach their account and the support routes. Disabled and closed users cannot sign in. Any status change deletes all of that user\'s sessions.');
  out.push('- **Evidence is labelled.** Milestone evidence is `self_reported` until a reviewer marks it `verified`; reports count only the latter as verified.');
  out.push('- **Mentor governance.** Mentors become visible only after the configured number of distinct reviewer approvals; reviewers can recuse; a mentor can be suspended; a mentor cannot match with themselves.');
  out.push('- **Database row-level security is not used.** SQLite has none. Enforcement is in the application layer and is covered by the all-routes authentication and permission test (`apps/api/test/security.test.ts`).', '');
  return out.join('\n');
}

const files: [string, string][] = [
  [path.join(docsDir, 'API.md'), markdown()],
  [path.join(docsDir, 'openapi.json'), JSON.stringify(openapi(), null, 2) + '\n'],
  [path.join(docsDir, 'PERMISSIONS.md'), permissionsDoc()],
];

if (process.argv.includes('--check')) {
  const stale = files.filter(([f, content]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== content).map(([f]) => path.relative(root, f));
  if (stale.length) { console.error(`Out of date: ${stale.join(', ')}. Run: npm run docs:api`); process.exit(1); }
  console.log(`API docs are up to date (${routes.length} endpoints).`);
} else {
  fs.mkdirSync(docsDir, { recursive: true });
  for (const [f, content] of files) fs.writeFileSync(f, content);
  console.log(`Wrote docs/API.md, docs/openapi.json and docs/PERMISSIONS.md (${routes.length} endpoints).`);
}
