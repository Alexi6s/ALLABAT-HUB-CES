// Generates docs/DATABASE.md from the real schema: migrations are applied to an in-memory SQLite database and inspected.
//
//   npm run docs:db              write docs/DATABASE.md
//   npm run docs:db -- --check   exit 1 if the committed file is out of date (used in CI and tests)
import fs from 'node:fs';
import path from 'node:path';
import { openDb, closeDb } from '../apps/api/src/core.ts';

const root = path.resolve(import.meta.dirname, '..');
const target = path.join(root, 'docs', 'DATABASE.md');

// Data classification is a human judgement, so it is written here by hand. The generator fails if a table named below no longer exists,
// so this list cannot silently go stale.
const CLASSIFICATION: Record<string, string> = {
  users: 'Personal data (name, email, phone, country). Password stored only as a salted scrypt hash.',
  sessions: 'Security data: only a SHA-256 hash of each session token is stored, with its expiry and the client IP.',
  auth_tokens: 'Security data: only hashes of single-use email-confirmation and password-reset tokens.',
  affiliations: 'Personal data (institution, ID number, department, graduation year).',
  consents: 'Record of which policy version each user accepted, and when.',
  documents: 'Sensitive: metadata for private identity and credential documents. The files themselves are in the private uploads directory and are never served statically.',
  verification_requests: 'Sensitive: identity-verification evidence references and reviewer decisions.',
  mentor_applications: 'Personal and professional data supplied by mentor applicants, including conflict declarations.',
  email_outbox: 'Contains the full message body, including single-use links, in clear text. No email provider is connected, so rows are only queued (status queued_no_provider) and nothing is sent.',
  audit_events: 'Operational record of who did what and when. The application only ever inserts into it; the database does not enforce immutability (no triggers), so restrict direct database access.',
};

const db = openDb(':memory:');
type Col = { cid: number; name: string; type: string; notnull: number; dflt_value: string | null; pk: number };
const tables = (db.prepare("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all() as { name: string; sql: string }[]);
const names = new Set(tables.map((t) => t.name));
for (const t of Object.keys(CLASSIFICATION)) if (!names.has(t)) throw new Error(`gen-db-docs: classification names a table that does not exist: ${t}`);

const out: string[] = [];
out.push('# Database schema', '');
out.push('_Generated by `npm run docs:db` from the migrations in `apps/api/migrations/`. Do not edit by hand._', '');
out.push(`SQLite (WAL mode, foreign keys enforced). ${tables.length} tables. Migrations run automatically at start-up and are recorded in \`schema_migrations\`.`, '');
out.push('Business rules that the database itself enforces: CHECK constraints on every status column, foreign keys, and partial unique indexes that make duplicate open requests, duplicate active mentorships and repeat mentor reviews impossible even under concurrent requests. Everything else (state transitions, capacity, separation of duties) is enforced in the API inside `BEGIN IMMEDIATE` transactions.', '');
out.push('## Data classification', '', '| Table | Classification |', '|---|---|');
for (const [t, c] of Object.entries(CLASSIFICATION)) out.push(`| \`${t}\` | ${c} |`);
out.push('', 'Tables not listed hold operational records (ventures, programmes, workshops, funding, milestones, resources, notifications) that may still be confidential to the people involved; access to them is controlled by the permission model in `PERMISSIONS.md`.', '');
out.push('## Tables', '');
for (const t of tables) {
  const cols = db.prepare(`PRAGMA table_info(${t.name})`).all() as Col[];
  const fks = db.prepare(`PRAGMA foreign_key_list(${t.name})`).all() as { from: string; table: string; to: string; on_delete: string }[];
  const idx = db.prepare(`PRAGMA index_list(${t.name})`).all() as { name: string; unique: number; origin: string; partial: number }[];
  out.push(`### ${t.name}`, '');
  out.push('| Column | Type | Required | Default | Key |', '|---|---|---|---|---|');
  for (const c of cols) {
    const fk = fks.find((f) => f.from === c.name);
    const key = [c.pk ? 'PK' : '', fk ? `FK → ${fk.table}(${fk.to})${fk.on_delete && fk.on_delete !== 'NO ACTION' ? ` on delete ${fk.on_delete.toLowerCase()}` : ''}` : ''].filter(Boolean).join(', ');
    out.push(`| ${c.name} | ${c.type || ''} | ${c.notnull || c.pk ? 'yes' : ''} | ${c.dflt_value ?? ''} | ${key} |`);
  }
  const named = idx.filter((i) => i.origin !== 'pk');
  if (named.length) {
    out.push('', 'Indexes:');
    for (const i of named) {
      const cols2 = (db.prepare(`PRAGMA index_info(${i.name})`).all() as { name: string }[]).map((c) => c.name).join(', ');
      out.push(`- \`${i.name}\` (${cols2})${i.unique ? ', unique' : ''}${i.partial ? ', partial' : ''}`);
    }
  }
  out.push('');
}
closeDb();
const content = out.join('\n');

if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) { console.error('docs/DATABASE.md is out of date. Run: npm run docs:db'); process.exit(1); }
  console.log(`Database docs are up to date (${tables.length} tables).`);
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, content);
  console.log(`Wrote docs/DATABASE.md (${tables.length} tables).`);
}
